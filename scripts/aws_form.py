#!/usr/bin/env python3
"""The pack choice on the AWS (CloudFormation) form, generated from packs/deploy-options.json so the form cannot disagree with what the charts can deploy (docs/agency-design.md, phase 6).

  python3 scripts/aws_form.py check       fail if the generated blocks in resource-manager/omnigateeksstack/template.yaml are out of date
  python3 scripts/aws_form.py generate    rewrite them

Two blocks sit between `# >>> generated by scripts/aws_form.py` and `# <<<` markers: the `DemoPacks` parameter (its description lists the packs with their size and what a mix costs) and the `Rules`
section. CloudFormation has no multi-select control for a custom parameter, so the parameter is a comma-separated list; the Rules check it on the form and show their message in the Console:
every item must be a known pack, the Smithsonian pack needs all six, and Demo packs and the older single Demo data dropdown must not be used together."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
TEMPLATE = os.path.join(ROOT, "resource-manager/omnigateeksstack/template.yaml")
OPTS = os.path.join(ROOT, "packs/deploy-options.json")
BEGIN, END = "# >>> generated by scripts/aws_form.py", "# <<<"


def quote(s): return json.dumps(s, ensure_ascii=False)          # a JSON string is a valid YAML double-quoted scalar


def description(o):
    packs = [p for p in o["packs"]]
    byid = {p["id"]: p for p in packs}
    order = ["supply-chain", "manufacturing", "it-risk", "smithsonian", "bom", "treasury"]
    items = []
    for i in order:
        p = byid[i]; extra = []
        if p["tables"]: extra.append("%d tables" % p["tables"])
        extra.append("%d approved questions" % p["approvedQuestions"])
        if p["needs"]: extra.append("adds " + " and ".join({"mariadb": "MariaDB", "embedding": "an embedding model", "objectStore": "an object store"}[n] for n in p["needs"]))
        items.append("%s (%s)" % (i, ", ".join(extra)))
    c = o["components"]
    cost = ("A mix costs the base (%d Mi of memory requests) plus each extra piece once: MariaDB +%d Mi, the embedding model +%d Mi. So any mix with treasury, and all six, request %d Mi, "
            "which used 83%% of a t4g.medium node when measured: do not go below t4g.medium." % (c["base"]["memoryMi"], c["mariadb"]["memoryMi"], c["embedding"]["memoryMi"],
                                                                                              c["base"]["memoryMi"] + c["mariadb"]["memoryMi"] + c["embedding"]["memoryMi"]))
    issues = " ".join("Known issue: " + k["text"].split(" Reported by")[0] for k in o.get("knownIssues", []))
    return ("Optional. Which packs a new install gets, as a comma-separated list, for example: bom,treasury. Leave empty to use Demo data instead. Packs: " + "; ".join(items) + ". "
            "manufacturing brings supply-chain along. smithsonian (needs outbound access to raw.githubusercontent.com) is only deployed with all six. "
            + cost + " " + issues + " bom and treasury need outbound access to huggingface.co. Read on a fresh install only: changing it on an existing stack does not reseed.")


def parameter_block(o):
    return "\n".join(["  " + BEGIN + " (parameter DemoPacks)", "  DemoPacks:", "    Type: CommaDelimitedList", '    Default: ""', "    Description: " + quote(description(o)), "  " + END])


def rules_block(o):
    known = ["", "supply-chain", "manufacturing", "it-risk", "smithsonian", "bom", "treasury"]
    others = ["supply-chain", "manufacturing", "it-risk", "bom", "treasury"]
    L = [BEGIN + " (Rules)", "Rules:",
         "  PacksAreKnown:",
         "    Assertions:",
         "      - Assert:",
         "          Fn::EachMemberIn:",
         "            - !Ref DemoPacks",
         "            - [%s]" % ", ".join(quote(k) for k in known),
         "        AssertDescription: " + quote("Demo packs: use only supply-chain, manufacturing, it-risk, smithsonian, bom and treasury, separated by commas (for example bom,treasury), or leave it empty."),
         "  SmithsonianNeedsAllPacks:",
         "    RuleCondition:",
         "      Fn::Contains:",
         "        - !Ref DemoPacks",
         "        - smithsonian",
         "    Assertions:",
         "      - Assert:",
         "          Fn::And:"]
    for k in others:
        L += ["            - Fn::Contains:", "                - !Ref DemoPacks", "                - " + k]
    L += ["        AssertDescription: " + quote("The Smithsonian pack (object store, loader, vocabulary) is only deployed together with all six packs for now: list every pack, or leave smithsonian out."),
          "  PacksOrDemoDataNotBoth:",
          "    RuleCondition:",
          "      Fn::Not:",
          "        - Fn::EachMemberEquals:",
          "            - !Ref DemoPacks",
          '            - ""',
          "    Assertions:",
          "      - Assert:",
          "          Fn::Equals:",
          "            - !Ref DemoDataset",
          "            - supply-chain",
          "        AssertDescription: " + quote("Use either Demo packs or Demo data, not both: leave Demo data at supply-chain when you list packs."),
          END]
    return "\n".join(L)


def splice(text, key, block):
    start = text.index(BEGIN + " (" + key + ")") if (BEGIN + " (" + key + ")") in text else -1
    if start < 0: raise SystemExit("marker for %s not found in the template" % key)
    # the marker line may be indented: back up to the start of its line
    line_start = text.rfind("\n", 0, start) + 1
    end = text.index(END, start) + len(END)
    return text[:line_start] + block + text[end:]


def build(text):
    o = json.load(open(OPTS))
    text = splice(text, "parameter DemoPacks", parameter_block(o))
    return splice(text, "Rules", rules_block(o))


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "check"
    cur = open(TEMPLATE).read(); want = build(cur)
    if cmd == "generate": open(TEMPLATE, "w").write(want); print("rewrote the generated blocks"); return 0
    if cur != want: print("out of date (run: python3 scripts/aws_form.py generate)"); return 1
    print("ok: the AWS form's pack choice is current"); return 0


if __name__ == "__main__": sys.exit(main(sys.argv))
