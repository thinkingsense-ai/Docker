#!/usr/bin/env python3
"""Pack manifests -> catalogue and Workspace config (docs/agency-design.md, phase 1).

  python3 scripts/packs.py check      validate every packs/*/pack.json against the real seeds and question files, and that the generated files are current
  python3 scripts/packs.py generate   rewrite packs/catalogue.json and packs/workspaces.yaml

Counts (tables, questions, questions that join two sources) are computed from the seeds and question files, never typed into a manifest.
Nothing here is read by a stack yet: this is the single description of a pack that the deploy forms, the Ask/Agency picker and Claude's tools will share."""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKS = os.path.join(ROOT, "packs")
REQUIRED = ("id", "title", "summary", "sources", "questions", "modalities", "inAllPacks", "editions", "licence")
TABLE_RE = re.compile(r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[`\"\w.]+", re.I)
REF_RE = re.compile(r"\b(pg|mdb|files)\.([a-z_]+)(?:\.([a-z_]+))?")


def load_manifests():
    out = []
    for name in sorted(os.listdir(PACKS)):
        path = os.path.join(PACKS, name, "pack.json")
        if os.path.isfile(path):
            out.append(json.load(open(path)))
    return out


def questions_for(p):
    q = p["questions"]
    rows = json.load(open(os.path.join(ROOT, q["file"])))
    cat = q.get("category")
    return [r for r in rows if cat is None or (r.get("category") or "").lower() == cat]


def sources_in(sql):
    return {m.group(1) for m in REF_RE.finditer(sql)}


def problems(p, qs):
    bad = []
    for k in REQUIRED:
        if k not in p:
            bad.append("%s: missing %s" % (p.get("id"), k))
    if bad:
        return bad
    declared = {(s["id"], sch) for s in p["sources"] for sch in s["schemas"]}
    if not qs:
        bad.append("%s: no questions found for category %r in %s" % (p["id"], p["questions"].get("category"), p["questions"]["file"]))
    for q in qs:
        for m in REF_RE.finditer(q["referenceSql"]):
            # files.museums has no schema level: the second group is the table
            ref = (m.group(1), m.group(2))
            if ref not in declared:
                bad.append("%s: question uses %s.%s which the manifest does not declare: %s" % (p["id"], m.group(1), m.group(2), q["question"][:60]))
    for s in p.get("seeds", []):
        if not os.path.isfile(os.path.join(ROOT, s)):
            bad.append("%s: seed %s not found" % (p["id"], s))
    return bad


def entry(p, qs):
    tables = None
    if p.get("seeds"):
        tables = sum(len(TABLE_RE.findall(open(os.path.join(ROOT, s)).read())) for s in p["seeds"])
    return {
        "id": p["id"], "title": p["title"], "summary": p["summary"], "extends": p.get("extends"), "demoDataset": p.get("demoDataset"),
        "sources": p["sources"], "tables": tables,
        "questions": {"approved": len(qs), "crossSource": sum(1 for q in qs if len(sources_in(q["referenceSql"])) > 1)},
        "modalities": p["modalities"], "needsEmbeddingModel": p.get("needsEmbeddingModel", False), "capabilities": p.get("capabilities", []),
        "inAllPacks": p["inAllPacks"], "editions": p["editions"], "licence": p["licence"],
    }


def catalogue(ms):
    es = []
    for p in ms:
        es.append(entry(p, questions_for(p)))
    return json.dumps({"packs": es}, indent=2, ensure_ascii=False) + "\n"


def workspaces(ms):
    lines = ["# Generated by scripts/packs.py from packs/*/pack.json. Do not edit; run `python3 scripts/packs.py generate`.",
             "# Value for OMNIGATE_NAMESPACE_CONFIG on the all-packs stack (backends pg, mdb, files).",
             "# A Workspace scopes by backend only: every pack on `pg` still sees every Postgres schema. Schema-level scope needs a Server change",
             "# (docs/agency-design.md, \"A pack is a Workspace\"); until then the catalogue's `sources[].schemas` is the intended scope.",
             "namespaces:"]
    for p in ms:
        if not p["inAllPacks"]:
            continue
        lines += ["  - id: %s" % p["id"], "    name: %s" % json.dumps(p["title"]),
                  "    backends: [%s]" % ", ".join(json.dumps(s["id"]) for s in p["sources"])]
    return "\n".join(lines) + "\n"


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "check"
    ms = load_manifests()
    bad = []
    for p in ms:
        bad += problems(p, questions_for(p) if "questions" in p else [])
    if bad:
        print("\n".join(bad)); return 1
    cat, ws = catalogue(ms), workspaces(ms)
    files = {os.path.join(PACKS, "catalogue.json"): cat, os.path.join(PACKS, "workspaces.yaml"): ws}
    if cmd == "generate":
        for path, text in files.items():
            open(path, "w").write(text)
        print("wrote %d files for %d packs" % (len(files), len(ms))); return 0
    stale = [os.path.relpath(p, ROOT) for p, t in files.items() if not os.path.isfile(p) or open(p).read() != t]
    if stale:
        print("out of date (run: python3 scripts/packs.py generate): " + ", ".join(stale)); return 1
    print("ok: %d packs, catalogue and workspaces current" % len(ms)); return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
